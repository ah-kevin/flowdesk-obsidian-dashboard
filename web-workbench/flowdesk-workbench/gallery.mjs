import { constants } from 'node:fs';
import { open, readdir, readFile, realpath, stat } from 'node:fs/promises';
import { dirname, join, posix } from 'node:path';
import { pipeline } from 'node:stream/promises';

const galleryRoot = 'Attachments/archify';
export const galleryVaultPath = galleryRoot + '/niubu-系统总览/index.html';
export const galleryCollectionsRoute = '/gallery/collections/';
const indexName = 'index.html';
const digestModule = 'gallery-sha256.mjs';
const excludedDirs = new Set(['.meta', 'tmp', 'reference', 'source']);
const imageTypes = new Map([
  ['.png', 'image/png'], ['.jpg', 'image/jpeg'], ['.jpeg', 'image/jpeg'], ['.gif', 'image/gif'],
  ['.webp', 'image/webp'], ['.avif', 'image/avif'], ['.svg', 'image/svg+xml'],
]);
const pageType = 'text/html; charset=utf-8';
const inspectLimit = 256 * 1024;
const manifestLimit = 512 * 1024;
const galleryPolicy = [
  "default-src 'none'",
  "script-src 'self' 'unsafe-inline'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "font-src 'self' data:",
  "media-src 'self' data: blob:",
  "frame-src 'self' blob:",
  "frame-ancestors 'self'",
  "form-action 'none'",
].join('; ');

function prepareIndex(index, hashFallback) {
  const guard = 'if (!crypto.subtle || !/^[a-f0-9]{64}$/.test(sha))';
  const digest = "Array.from(new Uint8Array(await crypto.subtle.digest('SHA-256', bytes)), byte => byte.toString(16).padStart(2, '0')).join('')";
  const digestLine = 'const hash = ' + digest + ';';
  if (!index.includes(guard) || !index.includes(digestLine)) return null;
  // Keep the generated byte count and SHA-256 checks on plain HTTP, where Web Crypto is unavailable.
  return Buffer.from(index.replace(guard, 'if (!/^[a-f0-9]{64}$/.test(sha))')
    .replace(digestLine, "const hash = crypto.subtle ? " + digest + " : " + hashFallback + ";"));
}

function sendBytes(request, response, bytes, type) {
  response.writeHead(200, { 'Content-Type': type, 'Content-Length': bytes.length });
  response.end(request.method === 'HEAD' ? undefined : bytes);
}

function setGalleryHeaders(response, mounted) {
  response.setHeader('Content-Security-Policy', galleryPolicy + (mounted ? '; sandbox allow-scripts allow-downloads allow-popups' : ''));
  response.setHeader('Referrer-Policy', 'no-referrer');
  response.setHeader('X-Content-Type-Options', 'nosniff');
  response.setHeader('Cache-Control', 'no-store');
}

let hashScript;
async function prepareMountedIndex(index) {
  const compatible = prepareIndex(index, 'globalThis.sha256(bytes)');
  if (!compatible) return null;
  hashScript ??= readFile(new URL(import.meta.resolve('js-sha256/build/sha256.min.js')), 'utf8');
  const script = '<script>' + (await hashScript).replace(/<\/script/gi, '<\\/script') + '</script>';
  const html = compatible.toString('utf8');
  return Buffer.from(/<head\b[^>]*>/i.test(html) ? html.replace(/<head\b[^>]*>/i, head => head + script) : script + html);
}

function safeGalleryName(name) {
  return Boolean(name && !name.startsWith('.') && !/[\\/\u0000-\u001f\u007f]/u.test(name));
}

function galleryPathInfo(path) {
  if (!path.startsWith(galleryRoot + '/')) return null;
  const parts = path.slice(galleryRoot.length + 1).split('/');
  if (parts.length < 2 || !parts.every(safeGalleryName) || parts.slice(0, -1).some(part => excludedDirs.has(part))
    || /\.archify-original\.html$|残留/iu.test(path)) return null;
  const extension = posix.extname(parts.at(-1)).toLowerCase();
  const kind = extension === '.html' ? 'page' : imageTypes.has(extension) ? 'image' : null;
  if (!kind) return null;
  return { kind, type: kind === 'page' ? pageType : imageTypes.get(extension), collection: parts[0],
    isEntry: parts.length === 2 && parts[1].toLowerCase() === indexName,
    href: galleryCollectionsRoute + parts.map(encodeURIComponent).join('/') };
}

function cleanHTML(value) {
  const entities = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ' };
  return value.replace(/<[^>]*>/gu, ' ').replace(/&(#x[\da-f]+|#\d+|[a-z]+);/giu, (whole, code) => {
    if (!code.startsWith('#')) {
      const key = code.toLowerCase();
      return Object.hasOwn(entities, key) ? entities[key] : whole;
    }
    const number = /^#x/i.test(code) ? Number.parseInt(code.slice(2), 16) : Number(code.slice(1));
    return number > 0 && number <= 0x10ffff ? String.fromCodePoint(number) : whole;
  }).replace(/\s+/gu, ' ').trim();
}

async function readGalleryPage(vault, path, { size, mtimeMs }, cache) {
  const cached = cache.get(path);
  if (cached?.size === size && cached.mtimeMs === mtimeMs) return cached.page;
  const file = await open(join(vault, path), constants.O_RDONLY | constants.O_NOFOLLOW | constants.O_NONBLOCK);
  try {
    const buffer = Buffer.alloc(Math.min(size, inspectLimit));
    const { bytesRead } = await file.read(buffer);
    const html = buffer.toString('utf8', 0, bytesRead).replace(/<(script|style)\b[^>]*>[\s\S]*?(?:<\/\1\s*>|$)/gi, ' ');
    const title = cleanHTML(/<title\b[^>]*>([\s\S]*?)<\/title>/i.exec(html)?.[1] || '')
      || cleanHTML(/<h1\b[^>]*>([\s\S]*?)<\/h1>/i.exec(html)?.[1] || '') || posix.basename(path, posix.extname(path));
    const text = Array.from(html.matchAll(/<(h[1-4]|p|li|td|th|text)\b[^>]*>([\s\S]*?)<\/\1>/gi), match => cleanHTML(match[2]));
    const page = { title, searchText: [...new Set(text.filter(Boolean))].join(' ').slice(0, 1600) };
    cache.set(path, { size, mtimeMs, page });
    return page;
  } finally {
    await file.close();
  }
}

async function galleryDocument(vault, collection, documents) {
  const path = join(vault, galleryRoot, collection, 'artifacts.json');
  try {
    if (await realpath(path) !== path || (await stat(path)).size > manifestLimit) return null;
    const manifest = JSON.parse(await readFile(path, 'utf8'));
    const artifact = Array.isArray(manifest?.artifacts) ? manifest.artifacts.find(item =>
      typeof item?.document === 'string' || typeof item?.document?.path === 'string')?.document : null;
    const target = manifest?.document?.path ?? (typeof artifact === 'string' ? artifact : artifact?.path);
    return typeof target === 'string' ? documents.get(target.normalize('NFC')) ?? null : null;
  } catch {
    // A missing or unreadable manifest only removes its optional document relation.
    return null;
  }
}

export function createGalleryCatalog(vault) {
  const cache = new Map();
  return async (documents, projectOptions) => {
    const files = new Map();
    const byDocument = new Map(documents.map(document => [document.path.normalize('NFC'), document]));
    const projectNames = projectOptions.map(project => posix.basename(project.path, '.md')).sort((a, b) => b.length - a.length);
    let unreadable = 0;
    async function scan(directory) {
      let children;
      try {
        const expected = join(vault, directory);
        if ((await realpath(expected)).normalize('NFC') !== expected.normalize('NFC')) return;
        children = await readdir(expected, { withFileTypes: true });
      } catch (error) {
        if (error.code !== 'ENOENT' || directory !== galleryRoot) unreadable++;
        return;
      }
      for (const child of children) {
        if (!safeGalleryName(child.name)) continue;
        const path = directory + '/' + child.name;
        if (child.isDirectory()) {
          if (!excludedDirs.has(child.name)) await scan(path);
          continue;
        }
        const info = child.isFile() && galleryPathInfo(path);
        if (!info) continue;
        try {
          const stats = await stat(join(vault, path));
          if (!stats.isFile()) continue;
          const page = info.kind === 'page' ? await readGalleryPage(vault, path, stats, cache) : null;
          files.set(path.normalize('NFC'), { ...info, ...page, path, mtime: stats.mtimeMs });
        } catch {
          unreadable++;
        }
      }
    }
    await scan(galleryRoot);
    for (const path of cache.keys()) if (!files.has(path.normalize('NFC'))) cache.delete(path);
    const collections = new Map();
    for (const file of files.values()) {
      if (file.kind !== 'page') continue;
      if (!collections.has(file.collection)) collections.set(file.collection, []);
      collections.get(file.collection).push(file);
    }
    const galleries = await Promise.all([...collections].map(async ([id, entries]) => {
      const entry = entries.find(file => file.isEntry);
      const document = await galleryDocument(vault, id, byDocument);
      const fallbackProject = projectNames.find(name => id.toLowerCase().startsWith(name.toLowerCase()));
      const pages = entries.filter(file => !file.isEntry).sort((a, b) => a.path.localeCompare(b.path, 'zh-CN', { numeric: true }))
        .map(({ title, href, searchText }) => ({ title, href, searchText }));
      const mtime = Math.max(...entries.map(file => file.mtime));
      return {
        id, kind: 'atlas', title: entry?.title || document?.title || id,
        projects: document?.projects?.length ? document.projects : fallbackProject ? [fallbackProject] : [],
        documentPath: document?.path ?? null, summary: document?.summary ?? '',
        href: entry?.href ?? (pages.length === 1 ? pages[0].href : null),
        pages, mtime, updatedAt: new Date(mtime).toISOString(), searchText: [id, entry?.searchText].filter(Boolean).join(' '),
      };
    }));
    return { files, galleries: galleries.sort((a, b) => b.mtime - a.mtime || a.title.localeCompare(b.title, 'zh-CN')), unreadable };
  };
}

export async function serveGalleryCollection(vault, catalog, pathname, request, response) {
  setGalleryHeaders(response, true);
  if (request.method !== 'GET' && request.method !== 'HEAD') return response.writeHead(405, { Allow: 'GET, HEAD' }).end();
  let parts;
  try {
    parts = pathname.slice(galleryCollectionsRoute.length).split('/').map(decodeURIComponent);
  } catch {
    return response.writeHead(404).end();
  }
  if (!parts.every(safeGalleryName)) return response.writeHead(404).end();
  const entry = catalog.files.get((galleryRoot + '/' + parts.join('/')).normalize('NFC'));
  if (!entry) return response.writeHead(404).end();
  let file;
  try {
    const expected = join(vault, entry.path);
    const actual = await realpath(expected);
    if (actual.normalize('NFC') !== expected.normalize('NFC')) return response.writeHead(404).end();
    file = await open(actual, constants.O_RDONLY | constants.O_NOFOLLOW | constants.O_NONBLOCK);
    const info = await file.stat();
    if (!info.isFile()) return response.writeHead(404).end();
    if (entry.isEntry) {
      const original = await file.readFile();
      const compatible = await prepareMountedIndex(original.toString('utf8'));
      return sendBytes(request, response, compatible ?? original, entry.type);
    }
    response.writeHead(200, { 'Content-Type': entry.type, 'Content-Length': info.size });
    if (request.method === 'HEAD') return response.end();
    await pipeline(file.createReadStream({ autoClose: false }), response);
  } catch (error) {
    if (response.headersSent) response.destroy();
    else response.writeHead(['ENOENT', 'ENOTDIR', 'ELOOP'].includes(error.code) ? 404 : 500).end();
  } finally {
    await file?.close().catch(() => {});
  }
}

export async function createGalleryHandler(galleryDir, { mounted = false } = {}) {
  const directory = await realpath(galleryDir);
  const indexPath = join(directory, indexName);
  if (await realpath(indexPath) !== indexPath) throw new Error('图集入口须位于图集目录内。');
  const index = await readFile(indexPath, 'utf8');
  const links = index.matchAll(/<a\b[^>]*\shref=["'](pages\/[a-z0-9-]+\.html)["']/gi);
  const allowedFiles = new Set([indexName, ...Array.from(links, ([, file]) => file)]);
  const compatibleIndex = mounted ? await prepareMountedIndex(index) : prepareIndex(index,
    "(await import('/" + digestModule + "')).sha256(bytes)");
  const fallback = !mounted && compatibleIndex && await readFile(new URL(import.meta.resolve('js-sha256/build/sha256.min.mjs')));

  return async (request, response) => {
    setGalleryHeaders(response, mounted);
    if (request.method !== 'GET' && request.method !== 'HEAD') return response.writeHead(405, { Allow: 'GET, HEAD' }).end();

    let path = request.url?.split('?', 1)[0];
    if (mounted) {
      if (path === '/gallery') return response.writeHead(308, { Location: '/gallery/' }).end();
      if (!path?.startsWith('/gallery/')) return response.writeHead(404).end();
      path = path.slice('/gallery'.length);
    }
    if (path === '/' + digestModule && fallback) return sendBytes(request, response, fallback, 'text/javascript; charset=utf-8');
    const name = path === '/' ? indexName : path?.slice(1);
    if (!path?.startsWith('/') || !allowedFiles.has(name)) return response.writeHead(404).end();

    const filename = join(directory, name);
    let file;
    try {
      if (await realpath(filename) !== filename) return response.writeHead(404).end();
      if (name === indexName && compatibleIndex) return sendBytes(request, response, compatibleIndex, 'text/html; charset=utf-8');
      file = await open(filename, constants.O_RDONLY | constants.O_NOFOLLOW | constants.O_NONBLOCK);
      const info = await file.stat();
      if (!info.isFile()) return response.writeHead(404).end();
      response.writeHead(200, { 'Content-Type': 'text/html; charset=utf-8', 'Content-Length': info.size });
      if (request.method === 'HEAD') return response.end();
      await pipeline(file.createReadStream({ autoClose: false }), response);
    } catch (error) {
      if (response.headersSent) response.destroy();
      else response.writeHead(['ENOENT', 'ENOTDIR', 'ELOOP'].includes(error.code) ? 404 : 500).end();
    } finally {
      await file?.close().catch(() => {});
    }
  };
}

export async function openGallery(vault) {
  const entry = join(vault, galleryVaultPath);
  try {
    if (await realpath(entry) !== entry) throw new Error('图集入口须位于 Vault 中的原图集目录内。');
  } catch (error) {
    if (error.code === 'ENOENT' || error.code === 'ENOTDIR') return null;
    throw error;
  }
  return createGalleryHandler(dirname(entry), { mounted: true });
}
